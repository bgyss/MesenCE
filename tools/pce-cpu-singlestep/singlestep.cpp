// Opcodes that are a different instruction (or a different addressing mode) on the
// HuC6280 than on the Rockwell 65C02, so the 65C02 result doesn't apply:
//   $x2/$x3/$x7-ish columns that the HuC6280 reuses: SXY SAX SAY ST0 ST1 ST2 TAM TMA
//   CLA CLX CLY TII TDD TIN TIA TAI TST BSR CSL CSH SET; BRK (vector $FFF6 on the
//   HuC6280), and the 65C02's multi-byte NOPs that are 1-byte NOPs on the HuC6280.
static const std::set<uint8_t> HucDiffersFrom65c02 = {
	0x00, // BRK: vector $FFF6 on the HuC6280
	0x02,
	0x22,
	0x42,
	0x62,
	0x82,
	0xC2,
	0xE2, // SXY SAX SAY CLA CLX CLY (NOP #imm on 65C02)
	0x03,
	0x13,
	0x23,
	0x33,
	0x43,
	0x53,
	0x63,
	0x73,
	0x83,
	0x93, // ST0 ST1 ST2 ... TMA TAM ... TII TST (1-byte NOPs on 65C02)
	0xA3,
	0xB3,
	0xC3,
	0xD3,
	0xE3,
	0xF3, // TST TDD TIN TIA TAI
	0x44,
	0x54,
	0xD4,
	0xF4, // BSR CSL CSH SET (NOP zp/zp,x on 65C02)
	0x5C,
	0xDC,
	0xFC, // NOP abs (3 bytes) on 65C02, 1-byte on HuC6280
};

static bool LoadJsonRegs(const json& s, CpuRegs& r)
{
	r.A = s["a"].get<uint8_t>();
	r.X = s["x"].get<uint8_t>();
	r.Y = s["y"].get<uint8_t>();
	r.S = s["s"].get<uint8_t>();
	r.P = s["p"].get<uint8_t>();
	r.PC = s["pc"].get<uint16_t>();
	// Logical pages 0 and 1 both map to physical bank 0, so the HuC6280's zero page
	// ($20xx) and stack ($21xx) land on the 65C02's $00xx and $01xx. Pages 2-7: identity.
	uint8_t mpr[8] = { 0, 0, 2, 3, 4, 5, 6, 7 };
	memcpy(r.Mpr, mpr, 8);
	return true;
}

static bool TouchesAliasRange(const json& t)
{
	auto inRange = [](uint32_t a) { return a >= 0x2000 && a < 0x4000; };
	for(const auto& e : t["initial"]["ram"]) {
		if(inRange(e[0].get<uint32_t>())) {
			return true;
		}
	}
	for(const auto& c : t["cycles"]) {
		if(!c[0].is_null() && inRange(c[0].get<uint32_t>())) {
			return true;
		}
	}
	return false;
}

// Known HuC6280-vs-65C02 differences in shared opcodes. Returns a category, or "" when
// the failure isn't explained (an unexpected failure). Where the HuC6280 is documented to
// differ, MesenCE's result is also checked against Mednafen's formula.
static string ClassifyR65c02(uint8_t opcode, const json& t, Harness& h)
{
	PceCpuState& st = h.Cpu->_state;
	const json& in = t["initial"];
	uint8_t a0 = in["a"].get<uint8_t>();
	uint8_t p0 = in["p"].get<uint8_t>() & ~0x20;
	const json& fin = t["final"];
	bool othersMatch = st.X == fin["x"].get<uint8_t>() && st.Y == fin["y"].get<uint8_t>() && st.SP == fin["s"].get<uint8_t>() && st.PC == fin["pc"].get<uint16_t>();

	// BIT #imm: the 65C02 only updates Z; the HuC6280 also copies bits 7/6 into N/V
	// (Mednafen: BIT sets N/V from the operand for every addressing mode)
	if(opcode == 0x89) {
		return "bit-imm-nv";
	}

	// TSB/TRB: on the HuC6280, N/V come from memory and Z from the result (Mednafen
	// TSB/TRB macros); on the 65C02 only Z changes, from A AND M
	if(opcode == 0x04 || opcode == 0x0C || opcode == 0x14 || opcode == 0x1C) {
		uint8_t m = 0;
		for(size_t i = 0; i < h.Bus.Ops.size(); i++) {
			if(h.Bus.Ops[i].Write) {
				m = h.Bus.Ops[i - 1].Value; // the value read just before the write-back
				break;
			}
		}
		bool trb = opcode == 0x14 || opcode == 0x1C;
		uint8_t result = trb ? (m & ~a0) : (m | a0);
		uint8_t p = (p0 & ~(0x02 | 0x40 | 0x80)) | (result ? 0 : 0x02) | (m & 0xC0);
		if(othersMatch && st.A == a0 && (st.PS & 0xDF) == (p & 0xDF)) {
			return "tsb-trb-flags";
		}
		return "";
	}

	// Decimal-mode ADC/SBC: compare with Mednafen's HuC6280 formula
	static const std::set<uint8_t> adc = { 0x61, 0x65, 0x69, 0x6D, 0x71, 0x72, 0x75, 0x79, 0x7D };
	static const std::set<uint8_t> sbc = { 0xE1, 0xE5, 0xE9, 0xED, 0xF1, 0xF2, 0xF5, 0xF9, 0xFD };
	if((adc.count(opcode) || sbc.count(opcode)) && (p0 & 0x08) && !h.Bus.Ops.empty()) {
		// The operand is the last value read before the decimal-mode dummy read
		uint8_t x = h.Bus.Ops[h.Bus.Ops.size() - 2].Value;
		if(othersMatch && MatchesMednafenDecimal(sbc.count(opcode) > 0, a0, x, p0, st.A, st.PS)) {
			return "decimal-adc-sbc";
		}
		// Invalid BCD digits: MesenCE's A/C/Z/N match the 65C02 (Mednafen differs there), and
		// only V differs, because the HuC6280 leaves V unchanged in decimal mode (Mednafen too)
		uint8_t pFin = fin["p"].get<uint8_t>();
		if(othersMatch && st.A == fin["a"].get<uint8_t>() && ((st.PS ^ pFin) & 0xDF) == 0x40 && (st.PS & 0x40) == (p0 & 0x40)) {
			return "decimal-adc-sbc";
		}
		return "";
	}

	// $DB: undefined on both chips. MesenCE runs it as a 1-byte NOP; the Rockwell suite
	// as a 2-byte one
	if(opcode == 0xDB && st.A == fin["a"].get<uint8_t>() && st.X == fin["x"].get<uint8_t>() && st.Y == fin["y"].get<uint8_t>()) {
		return "undefined-db";
	}
	return "";
}

static int RunR65c02(Harness& h, const json& t, string& detail)
{
	int kinds = 0;
	std::ostringstream d;
	h.Bus.Clear();
	CpuRegs ini, fin;
	LoadJsonRegs(t["initial"], ini);
	LoadJsonRegs(t["final"], fin);
	// Bit 5 is the T flag on the HuC6280 (always 1 on the 65C02): start with T clear
	ini.P &= ~0x20;
	for(const auto& e : t["initial"]["ram"]) {
		h.Bus.Poke(e[0].get<uint32_t>(), e[1].get<uint8_t>());
	}
	h.SetRegs(ini);
	h.Step();
	h.CheckRegs(fin, 0xDF, false, kinds, d); // P compared without bit 5 (T)
	for(const auto& e : t["final"]["ram"]) {
		uint32_t a = e[0].get<uint32_t>();
		uint8_t v = e[1].get<uint8_t>();
		uint8_t actual = h.Bus.Ram[a];
		// A pushed P (PHP) has bit 5 = 1 on the 65C02 and T (0) on the HuC6280
		if(actual != v && !((actual ^ v) == 0x20 && a >= 0x100 && a < 0x200)) {
			kinds |= FailRam;
			d << " [" << Hex(a, 4) << "]=" << Hex(actual, 2) << "(exp " << Hex(v, 2) << ")";
			break;
		}
	}
	detail = t["name"].get<string>() + ":" + d.str();
	return kinds;
}

// -------------------------------------------------------------------------------------

int main(int argc, char* argv[])
{
	int maxDetails = 3;
	string suite;
	vector<fs::path> files;
	for(int i = 1; i < argc; i++) {
		string a = argv[i];
		if(a == "--details" && i + 1 < argc) {
			maxDetails = std::stoi(argv[++i]);
		} else if(a == "--suite" && i + 1 < argc) {
			suite = argv[++i];
		} else if(fs::is_directory(a)) {
			for(const auto& e : fs::directory_iterator(a)) {
				string n = e.path().filename().string();
				if(n.size() > 5 && (n.substr(n.size() - 5) == ".json" || n.find(".json.bin") != string::npos)) {
					files.push_back(e.path());
				}
			}
		} else {
			files.push_back(a);
		}
	}
	std::sort(files.begin(), files.end());
	if(files.empty() || (suite != "huc6280" && suite != "r65c02")) {
		std::cerr << "usage: singlestep --suite huc6280|r65c02 [--details N] <file | dir> ...\n";
		return 2;
	}

	fs::path home = fs::temp_directory_path() / "mesen-pce-singlestep-home";
	fs::create_directories(home);
	FolderUtilities::SetHomeFolder(home.string());
	Emulator emu;
	emu.Initialize(false);

	Harness* h = new Harness();
	h->Cpu = new TestPceCpu(&emu, &h->Bus);
	h->Bus.IdleCycle = [h]() { h->Cpu->RunIdleCpuCycle(); };
	h->Bus.ModelVdcAccess = suite != "huc6280";

	uint64_t total = 0, failed = 0, known = 0, skipped = 0;
	int failedFiles = 0;
	std::map<string, uint64_t> knownCounts;
	for(const fs::path& f : files) {
		string name = f.filename().string();
		name = name.substr(0, name.find('.'));
		int fail = 0, shown = 0, run = 0;
		std::map<int, int> kindCounts;
		vector<string> details;
		auto record = [&](int k, const string& detail, const string& cls) {
			total++;
			run++;
			if(!k) {
				return;
			}
			if(!cls.empty()) {
				known++;
				knownCounts[cls]++;
				return;
			}
			fail++;
			kindCounts[k]++;
			if(shown++ < maxDetails) {
				details.push_back(detail);
			}
		};

		if(suite == "huc6280") {
			vector<HucTest> tests;
			if(!LoadHucTests(f, tests)) {
				continue;
			}
			uint8_t opcode = (uint8_t)std::stoul(name, nullptr, 16);
			for(const HucTest& t : tests) {
				// The generator stops recording after 500 cycles / 500 RAM pairs, so long
				// block transfers have no reliable expected state (suite README)
				if(t.NumCycles > t.Cycles.size()) {
					skipped++;
					continue;
				}
				string detail;
				int k = RunHuc(*h, t, detail);
				record(k, detail, k ? ClassifyHuc(opcode, t, *h, k) : "");
			}
		} else {
			uint8_t opcode = (uint8_t)std::stoul(name, nullptr, 16);
			if(HucDiffersFrom65c02.count(opcode)) {
				std::cout << "skip " << name << ": a different instruction on the HuC6280\n";
				continue;
			}
			std::ifstream in(f);
			json tests = json::parse(in);
			for(const json& t : tests) {
				if(TouchesAliasRange(t)) {
					skipped++;
					continue;
				}
				string detail;
				int k = RunR65c02(*h, t, detail);
				record(k, detail, k ? ClassifyR65c02(opcode, t, *h) : "");
			}
		}

		failed += fail;
		if(!fail) {
			continue;
		}
		failedFiles++;
		std::cout << "FAIL " << name << ": " << (run - fail) << "/" << run << " pass (";
		bool first = true;
		for(auto& [k, cnt] : kindCounts) {
			std::cout << (first ? "" : ", ") << cnt << "x" << ((k & FailRegs) ? " regs" : "") << ((k & FailRam) ? " ram" : "") << ((k & FailCycles) ? " cycles" : "") << ((k & FailBus) ? " bus" : "");
			first = false;
		}
		std::cout << ")\n";
		for(const string& s : details) {
			std::cout << "    " << s << "\n";
		}
	}
	for(auto& [cls, cnt] : knownCounts) {
		std::cout << "KNOWN " << cls << ": " << cnt << "\n";
	}
	std::cout << "TOTAL (" << suite << "): " << (total - failed - known) << "/" << total << " pass, " << failed << " unexpected fail (" << failedFiles << " files), " << known
				 << " known difference, " << skipped << " skipped\n";
	return failed ? 1 : 0;
}
