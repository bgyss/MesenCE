struct BusOp
{
	bool Write;
	uint32_t Addr; // physical
	uint8_t Value;
};

class TestPceCpu;

// Stands in for PceMemoryManager: the members PceCpu calls.
class TestBus
{
public:
	uint8_t* Ram = new uint8_t[0x200000]();
	vector<uint32_t> Touched;
	uint8_t Mpr[8] = {};
	uint8_t MprReadBuffer = 0;
	vector<BusOp> Ops;
	std::function<void()> IdleCycle;
	// PceMemoryManager::WriteVdc delays the CPU by one cycle (a memory-system effect, not
	// part of the CPU). The huc6280 suite's generator didn't model VDC accesses at all.
	bool ModelVdcAccess = true;

	uint32_t Phys(uint16_t addr) { return ((uint32_t)Mpr[addr >> 13] << 13) | (addr & 0x1FFF); }
	void Poke(uint32_t phys, uint8_t v)
	{
		Ram[phys & 0x1FFFFF] = v;
		Touched.push_back(phys & 0x1FFFFF);
	}
	void Clear()
	{
		for(uint32_t a : Touched) {
			Ram[a] = 0;
		}
		Touched.clear();
		Ops.clear();
	}

	uint8_t Read(uint16_t addr, MemoryOperationType = MemoryOperationType::Read)
	{
		uint32_t p = Phys(addr);
		Ops.push_back({ false, p, Ram[p] });
		return Ram[p];
	}
	void Write(uint16_t addr, uint8_t value, MemoryOperationType)
	{
		uint32_t p = Phys(addr);
		Ops.push_back({ true, p, value });
		Poke(p, value);
	}
	// ST0/ST1/ST2: VDC register write (bank $FF), plus the 1-cycle VDC delay
	void WriteVdc(uint16_t addr, uint8_t value)
	{
		if(ModelVdcAccess) {
			Ops.push_back({ true, (0xFFu << 13) | addr, value });
			IdleCycle();
		}
	}
	void Exec() {}
	void SetSpeed(bool) {}
	bool HasIrqSource(PceIrqSource) { return false; }
	uint8_t GetPendingIrqs() { return 0; }
	// Same as PceMemoryManager::SetMprValue / GetMprValue
	void SetMprValue(uint8_t regSelect, uint8_t value)
	{
		if(regSelect == 0) {
			return;
		}
		MprReadBuffer = value;
		for(int i = 0; i < 8; i++) {
			if(regSelect & (1 << i)) {
				Mpr[i] = value;
			}
		}
	}
	uint8_t GetMprValue(uint8_t regSelect)
	{
		if(regSelect == 0) {
			return MprReadBuffer;
		}
		uint8_t value = 0;
		for(int i = 0; i < 8; i++) {
			if(regSelect & (1 << i)) {
				value |= Mpr[i];
			}
		}
		return value;
	}
};

