// singlestep.cpp - differential tests of MesenCE's PC Engine CPU (PceCpu, HuC6280).
//
// Two suites, with different roles:
//
//  --suite huc6280  SingleStepTests/huc6280 (binary .json.bin). Generated FROM MESEN by
//                   its author, so it is not an independent source: it is a regression
//                   baseline that shows where MesenCE now differs from the Mesen version
//                   that generated it. Checked: registers, MPRs, RAM, cycle count, and
//                   the recorded bus cycles (read/write, 21-bit physical address, value).
//
//  --suite r65c02   SingleStepTests/65x02 rockwell65c02 (JSON). Generated by Thomas Harte's
//                   Clock Signal, independently of Mesen. The HuC6280 is a Rockwell 65C02
//                   derivative, so for the opcodes the two share, results must agree.
//                   Checked: registers and RAM only (bus activity and timing differ by
//                   design). The HuC6280 keeps its zero page and stack at logical
//                   $2000/$2100, so the harness maps logical pages 0 and 1 both to
//                   physical bank 0 (MPR0 = MPR1 = 0, MPRn = n otherwise): zero page and
//                   stack then land on the 65C02's $00xx/$01xx. Tests that touch
//                   $2000-$3FFF are skipped (that range aliases bank 0), as are opcodes
//                   that are different instructions on the HuC6280.
//
// The harness compiles the real PceCpu sources (PceCpu.cpp, PceCpu.Instructions.cpp) as
// "TestPceCpu", with PceMemoryManager replaced by TestBus (flat 2 MiB physical space
// behind the 8 MPRs).
//
// Usage: singlestep --suite huc6280|r65c02 [--details N] <file | dir> ...

