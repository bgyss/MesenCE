static string Hex(uint32_t v, int width)
{
	std::ostringstream ss;
	ss << std::hex << std::uppercase << std::setw(width) << std::setfill('0') << v;
	return ss.str();
}

enum FailKind
{
	FailRegs = 1,
	FailRam = 2,
	FailCycles = 4,
	FailBus = 8,
};

struct CpuRegs
{
	uint8_t A, X, Y, S, P;
	uint16_t PC;
	uint8_t Mpr[8];
};

struct Harness
{
	TestBus Bus;
	TestPceCpu* Cpu = nullptr;

	void SetRegs(const CpuRegs& r)
	{
		PceCpuState& st = Cpu->_state;
		st = {};
		st.A = r.A;
		st.X = r.X;
		st.Y = r.Y;
		st.SP = r.S;
		st.PS = r.P;
		st.PC = r.PC;
		memcpy(Bus.Mpr, r.Mpr, 8);
		Bus.MprReadBuffer = 0;
		Cpu->_pendingIrqs = 0;
	}

	uint64_t Step()
	{
		uint64_t start = Cpu->_state.CycleCount;
		Cpu->Exec();
		return Cpu->_state.CycleCount - start;
	}

	void CheckRegs(const CpuRegs& e, uint8_t pMask, bool checkMpr, int& kinds, std::ostringstream& d)
	{
		PceCpuState& st = Cpu->_state;
		auto chk = [&](const char* name, uint32_t a, uint32_t x, int w) {
			if(a != x) {
				kinds |= FailRegs;
				d << " " << name << "=" << Hex(a, w) << "(exp " << Hex(x, w) << ")";
			}
		};
		chk("A", st.A, e.A, 2);
		chk("X", st.X, e.X, 2);
		chk("Y", st.Y, e.Y, 2);
		chk("S", st.SP, e.S, 2);
		chk("P", st.PS & pMask, e.P & pMask, 2);
		chk("PC", st.PC, e.PC, 4);
		if(checkMpr) {
			for(int i = 0; i < 8; i++) {
				if(Bus.Mpr[i] != e.Mpr[i]) {
					kinds |= FailRegs;
					d << " MPR" << i << "=" << Hex(Bus.Mpr[i], 2) << "(exp " << Hex(e.Mpr[i], 2) << ")";
				}
			}
		}
	}
};

// --- SingleStepTests/huc6280 (binary) ---------------------------------------------

struct HucCycle
{
	bool Rd, Wr;
	uint32_t Addr;
	uint8_t Data;
};

struct HucTest
{
	string Name;
	CpuRegs Initial, Final;
	vector<std::pair<uint32_t, uint8_t>> InitialRam, FinalRam;
	uint32_t NumCycles;
	vector<HucCycle> Cycles;
};

static bool LoadHucTests(const fs::path& path, vector<HucTest>& tests)
{
	std::ifstream in(path, std::ios::binary);
	vector<uint8_t> buf((std::istreambuf_iterator<char>(in)), {});
	if(buf.size() < 4) {
		return false;
	}
	auto u32 = [&](size_t p) {
		uint32_t v;
		memcpy(&v, buf.data() + p, 4);
		return v;
	};
	uint32_t count = u32(0);
	size_t p = 4;
	auto loadState = [&](size_t q, CpuRegs& r, vector<std::pair<uint32_t, uint8_t>>& ram) {
		size_t full = u32(q);
		q += 4;
		r.A = buf[q];
		r.X = buf[q + 1];
		r.Y = buf[q + 2];
		r.S = buf[q + 3];
		r.P = buf[q + 4];
		q += 5;
		r.PC = buf[q] | (buf[q + 1] << 8);
		q += 2;
		memcpy(r.Mpr, &buf[q], 8);
		q += 8;
		uint32_t n = u32(q);
		q += 4;
		for(uint32_t i = 0; i < n; i++) {
			ram.push_back({ u32(q), buf[q + 4] });
			q += 5;
		}
		return full;
	};
	for(uint32_t i = 0; i < count; i++) {
		HucTest t;
		size_t full = u32(p);
		size_t q = p + 4;
		t.Name = string((const char*)&buf[q], strnlen((const char*)&buf[q], 50));
		q += 50 + 4; // name, opcode
		q += loadState(q, t.Initial, t.InitialRam);
		q += loadState(q, t.Final, t.FinalRam);
		t.NumCycles = u32(q);
		uint32_t rec = u32(q + 4);
		q += 8;
		for(uint32_t k = 0; k < rec; k++) {
			uint32_t c = u32(q + k * 4);
			t.Cycles.push_back({ (c & 1) != 0, ((c >> 1) & 1) != 0, (c >> 3) & 0x1FFFFF, (uint8_t)(c >> 24) });
		}
		tests.push_back(std::move(t));
		p += full;
	}
	return true;
}

// Mednafen's HuC6280 (libretro beetle-pce, mednafen/pce/huc6280.cpp) decimal-mode ADC/SBC:
// Z/N/C from the BCD result, V unchanged. Used as an independent reference for the cases
// where the HuC6280 is documented to differ from the 65C02.
static bool MatchesMednafenDecimal(bool sbc, uint8_t a, uint8_t x, uint8_t pIn, uint8_t actualA, uint8_t actualP)
{
	uint8_t carry = pIn & 1;
	uint8_t p = pIn & ~(0x02 | 0x80 | 0x01);
	uint8_t result;
	if(!sbc) {
		uint32_t tmp = (a & 0x0F) + (x & 0x0F) + carry;
		if(tmp >= 0x0A) {
			tmp += 0x06;
		}
		tmp += (a & 0xF0) + (x & 0xF0);
		if(tmp >= 0xA0) {
			tmp += 0x60;
		}
		if(tmp & 0xFF00) {
			p |= 0x01;
		}
		result = (uint8_t)tmp;
	} else {
		uint8_t m = (a & 0xF) - (x & 0xF) - (carry ^ 1);
		uint8_t n = (a >> 4) - (x >> 4) - ((m >> 4) & 1);
		result = (n << 4) | (m & 0xF);
		if(m & 0x10) {
			result -= 0x06;
		}
		if(n & 0x10) {
			result -= 0x60;
		}
		p |= ((n >> 4) & 0x1) ^ 1;
	}
	if(result == 0) {
		p |= 0x02;
	}
	p |= result & 0x80;
	return actualA == result && (actualP & 0xDF) == (p & 0xDF);
}

// Known differences between MesenCE and the huc6280 suite's generator. Returns "" if none.
static string ClassifyHuc(uint8_t opcode, const HucTest& t, Harness& h, int kinds)
{
	PceCpuState& st = h.Cpu->_state;
	// TSB/TRB: MesenCE (and Mednafen) set Z from the result; the generator used A AND M
	bool onlyZ = kinds == FailRegs && st.A == t.Final.A && st.X == t.Final.X && st.Y == t.Final.Y && st.SP == t.Final.S && st.PC == t.Final.PC &&
		(st.PS ^ t.Final.P) == 0x02;
	if((opcode == 0x04 || opcode == 0x0C || opcode == 0x14 || opcode == 0x1C) && onlyZ) {
		return "tsb-trb-z";
	}
	// Decimal-mode SBC with invalid BCD digits: fixed in this fork to match the 65C02 and
	// Mednafen; the generator recorded MesenCE's previous formula. Accepted only when the
	// new result matches Mednafen's.
	static const std::set<uint8_t> sbc = { 0xE1, 0xE5, 0xE9, 0xED, 0xF1, 0xF2, 0xF5, 0xF9, 0xFD };
	if(sbc.count(opcode) && (t.Initial.P & 0x08) && h.Bus.Ops.size() >= 2) {
		// The decimal-mode extra cycle is a dummy read of PC, or an idle cycle when the T
		// flag was set; the operand is the read before it
		bool tFlag = t.Initial.P & 0x20;
		uint8_t x = h.Bus.Ops[h.Bus.Ops.size() - (tFlag ? 1 : 2)].Value;
		bool othersMatch = st.X == t.Final.X && st.Y == t.Final.Y && st.SP == t.Final.S && st.PC == t.Final.PC;
		if(othersMatch && MatchesMednafenDecimal(true, t.Initial.A, x, t.Initial.P & ~0x20, st.A, st.PS)) {
			return "decimal-sbc-fixed";
		}
	}
	// TMA #$00 returns the last value written with TAM, which isn't part of a test's state
	if(opcode == 0x43) {
		uint32_t operandAddr = ((uint32_t)t.Initial.Mpr[(uint16_t)(t.Initial.PC + 1) >> 13] << 13) | ((t.Initial.PC + 1) & 0x1FFF);
		for(auto& [a, v] : t.InitialRam) {
			if(a == operandAddr && v == 0) {
				return "tma-zero";
			}
		}
	}
	return "";
}

static int RunHuc(Harness& h, const HucTest& t, string& detail)
{
	int kinds = 0;
	std::ostringstream d;
	h.Bus.Clear();
	for(auto& [a, v] : t.InitialRam) {
		h.Bus.Poke(a, v);
	}
	h.SetRegs(t.Initial);
	uint64_t cycles = h.Step();
	// Block transfers can run past the generator's 500-cycle recording limit
	bool truncated = t.NumCycles > t.Cycles.size();
	if(!truncated && cycles != t.NumCycles) {
		kinds |= FailCycles;
		d << " cycles=" << cycles << "(exp " << t.NumCycles << ")";
	}
	h.CheckRegs(t.Final, 0xFF, true, kinds, d);
	for(auto& [a, v] : t.FinalRam) {
		if(h.Bus.Ram[a & 0x1FFFFF] != v) {
			kinds |= FailRam;
			d << " [" << Hex(a, 6) << "]=" << Hex(h.Bus.Ram[a & 0x1FFFFF], 2) << "(exp " << Hex(v, 2) << ")";
			break;
		}
	}
	// Bus: the recorded read/write cycles, in order (idle cycles have neither)
	vector<BusOp> expected;
	for(const HucCycle& c : t.Cycles) {
		if(c.Rd || c.Wr) {
			expected.push_back({ c.Wr, c.Addr, c.Data });
		}
	}
	size_t n = truncated ? std::min(expected.size(), h.Bus.Ops.size()) : std::max(expected.size(), h.Bus.Ops.size());
	bool busOk = truncated || expected.size() == h.Bus.Ops.size();
	for(size_t i = 0; busOk && i < n; i++) {
		const BusOp& a = h.Bus.Ops[i];
		const BusOp& e = expected[i];
		busOk = a.Write == e.Write && a.Addr == e.Addr && a.Value == e.Value;
	}
	if(!busOk) {
		kinds |= FailBus;
		auto fmt = [](const vector<BusOp>& ops) {
			std::ostringstream ss;
			for(size_t i = 0; i < ops.size() && i < 12; i++) {
				ss << " " << (ops[i].Write ? "W" : "R") << Hex(ops[i].Addr, 6) << "=" << Hex(ops[i].Value, 2);
			}
			return ss.str();
		};
		d << "\n      actual bus:  " << fmt(h.Bus.Ops) << "\n      expected bus:" << fmt(expected);
	}
	detail = t.Name + ":" + d.str();
	return kinds;
}

