#!/usr/bin/env python3
"""32X output stage (findings C7): the mix is AC coupled, so a PWM level held away from the centre
leaves no DC in the output.

Runs the m32x_pwm cartridge (generated by tests/MD/synthetic/gen.py): after its samples play, the
FIFO is empty and the PWM holds its last pulse widths, one channel at full scale (the per-chip PWM
stream, taken before the mix, shows the DC). The mixed output's mean over the last half second must
be close to 0. Without the DC blocker it is the held PWM level.

Usage: pwm_dc_check.py <md-synthetic dir>
"""
import pathlib
import subprocess
import sys
import tempfile
import wave

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[3]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rom = pathlib.Path(sys.argv[1]) / "m32x_pwm.md"
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "run"
        proc = subprocess.run([str(ROOT / "bin/mesen-headless"), "run", "--rom", str(rom), "--frames", "120",
                               "--out", str(out), "--allow-dirty", "--region", "ntsc", "--md-model", "md1va3",
                               "--chip-audio"], capture_output=True, text=True)
        if proc.returncode != 0:
            print(f"FAIL 32x PWM DC: exit {proc.returncode}: {proc.stderr[-300:]}")
            sys.exit(1)
        pwm = np.frombuffer((out / "pwm.raw").read_bytes(), dtype="<i2").reshape(-1, 2).astype(float)
        with wave.open(str(out / "audio.wav")) as w:
            rate = w.getframerate()
            mix = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).reshape(-1, 2).astype(float)
    held = np.abs(pwm[-len(pwm) // 4:].mean(axis=0)).max()
    dc = np.abs(mix[-rate // 2:].mean(axis=0)).max()
    ok = held > 4000 and dc < 100
    print(f"{'ok  ' if ok else 'FAIL'} 32x PWM DC: held PWM level {held:.0f}, mix mean {dc:.1f}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
