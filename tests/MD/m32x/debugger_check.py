#!/usr/bin/env python3
"""32X debugger integration (S4): runs tests/MD/m32x/debugger.lua on the m32x_boot cartridge
(generated by tests/MD/synthetic/gen.py) (32X header: the unit attaches itself). The script checks the SH-2s'
exec callbacks and memory types and stops with 0 when all hold.

Usage: debugger_check.py <md-synthetic dir>
"""
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[3]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rom = pathlib.Path(sys.argv[1]) / "m32x_boot.md"
    script = ROOT / "tests/MD/m32x/debugger.lua"
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "run"
        proc = subprocess.run([str(ROOT / "bin/mesen-headless"), "run", "--rom", str(rom), "--frames", "10",
                               "--out", str(out), "--allow-dirty", "--lua", str(script)],
                              capture_output=True, text=True)
        log = (out / "lua.log").read_text() if (out / "lua.log").exists() else proc.stderr
    if proc.returncode != 0:
        print(log)
        print(f"FAIL 32x debugger: exit {proc.returncode}")
        sys.exit(1)
    print("ok   32x debugger (SH-2 exec/write callbacks, m32xMasterMemory/m32xSdram access, memory sizes)")


if __name__ == "__main__":
    main()
