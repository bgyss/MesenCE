#!/usr/bin/env python3
"""Sega CD debugger integration (S4): runs tests/MD/mcd/debugger.lua on the mcd_boot_comm cartridge
(generated by tests/MD/synthetic/gen.py) with the Mega CD unit attached. The script checks the sub CPU's
exec callbacks and memory types and stops with 0 when all hold.

Usage: debugger_check.py <md-synthetic dir>
"""
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[3]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rom = pathlib.Path(sys.argv[1]) / "mcd_boot_comm.md"
    script = ROOT / "tests/MD/mcd/debugger.lua"
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "run"
        proc = subprocess.run([str(ROOT / "bin/mesen-headless"), "run", "--rom", str(rom), "--frames", "10",
                               "--out", str(out), "--allow-dirty", "--md-mcd", "--lua", str(script)],
                              capture_output=True, text=True)
        log = (out / "lua.log").read_text() if (out / "lua.log").exists() else proc.stderr
    if proc.returncode != 0:
        print(log)
        print(f"FAIL mcd debugger: exit {proc.returncode}")
        sys.exit(1)
    print("ok   mcd debugger (sub CPU exec callback, mcdMemory/mcdPrgRam access, memory sizes)")


if __name__ == "__main__":
    main()
