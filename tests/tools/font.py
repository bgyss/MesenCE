def rows(ch):
    g = GLYPHS[ch]
    out = []
    for r in range(8):
        line = g[r] if r < len(g) else "....."
        v = 0
        for i, c in enumerate(line):
            if c == "#":
                v |= 0x80 >> (i + 1)  # 5 pixels in columns 1-5
        out.append(v)
    return out


def main():
    fmt = sys.argv[1] if len(sys.argv) > 1 else "wla"
    directive = ".DB" if fmt == "wla" else ".byte"
    comment = ";"
    print(f"{comment} Generated by tests/tools/font.py - characters $20-$5A, 8 bytes each")
    for code in range(0x20, 0x5B):
        ch = chr(code)
        data = ", ".join(f"${b:02X}" for b in rows(ch))
        print(f"{directive} {data} {comment} '{ch}'" if ch not in ";'" else f"{directive} {data} {comment} ${code:02X}")


if __name__ == "__main__":
    main()
